create table if not exists public.license_keys (
  id bigint generated by default as identity primary key,
  key text not null unique,
  name text not null default '',
  deviceid text,
  status text not null default 'active' check (status in ('active', 'expired', 'banned')),
  expireat timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists license_keys_deviceid_idx on public.license_keys (deviceid);
create index if not exists license_keys_status_idx on public.license_keys (status);

create table if not exists public.activation_requests (
  id bigint generated by default as identity primary key,
  deviceid text not null,
  fingerprint text not null default '',
  ip text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists activation_requests_deviceid_idx on public.activation_requests (deviceid);
create index if not exists activation_requests_created_at_idx on public.activation_requests (created_at desc);

-- The server uses the service-role key. Do not expose that key in the app.
-- Enable RLS if this database is also accessed by browser clients.
alter table public.license_keys enable row level security;

alter table public.activation_requests enable row level security;

create table if not exists public.backups (
  id bigint generated by default as identity primary key,
  license_key text not null,
  deviceid text not null,
  file_name text not null,
  storage_path text not null unique,
  size_bytes bigint not null default 0,
  metadata jsonb not null default '{}'::jsonb,
  claimed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists backups_license_key_idx on public.backups (license_key);
create index if not exists backups_deviceid_idx on public.backups (deviceid);
create index if not exists backups_created_at_idx on public.backups (created_at asc);

alter table public.backups enable row level security;
